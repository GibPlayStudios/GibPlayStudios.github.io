// Exports the Bitz art used on gibplay.com/Bitz/ with the app's own pixel
// renderer (the same code that draws the app, widgets and App Store art).
// Usage: swift run bitz-art <output-directory>
// Everything is written at native pixel size (1 art pixel = 1 image pixel) unless
// the name says otherwise; the site scales it up with `image-rendering: pixelated`.

let output = URL(fileURLWithPath: CommandLine.arguments.dropFirst().first ?? "out")
try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)

func save(_ canvas: PixelCanvas, _ name: String, scale: Int = 1) {
    let url = output.appendingPathComponent(name + ".png")
    try! PNGEncoder.encode(scale == 1 ? canvas : canvas.scaled(scale)).write(to: url)
    print("wrote", name + ".png", "\(canvas.width * scale)x\(canvas.height * scale)")
}

var calendar = Calendar(identifier: .gregorian)
calendar.timeZone = TimeZone(identifier: "UTC")!

/// The outfit Bitz wears on the site: the beanie and scarf from the App Store screenshots.
let siteOutfit: [OutfitSlot: Outfit] = [.neck: .scarf, .head: .beanie]

/// A furnished room of the home at a given hour and month (the preview tool's `homeScene`).
func homeRoom(_ home: HomeRoom, hour: Int, minute: Int = 30, month: Int = 10, theme: RoomTheme = .classic,
              outfits: [OutfitSlot: Outfit] = siteOutfit,
              configure: (inout BitzState, Date) -> Void = { _, _ in }) -> RoomSnapshot {
    let date = calendar.date(from: DateComponents(year: 2026, month: month, day: 20, hour: hour, minute: minute))!
    var state = BitzState(now: date.addingTimeInterval(-3600), seed: "gibplay-site")
    state.introTripPlanned = true
    state.tripsPlannedThrough = DayKey(year: 2100, month: 1, day: 1)
    state.ownedThemes = Set(RoomTheme.allCases)
    state.stars = 5000
    for decor in Decor.allCases where decor.room == home { try? state.buy(.decor(decor)) }
    try? state.useTheme(theme, in: home)
    state.ownedOutfits = Set(outfits.values)
    state.equipped = outfits
    configure(&state, date)
    return EnvironmentEngine.snapshot(state, at: date, calendar: calendar).placing(in: home)
}

func render(_ room: RoomSnapshot, cat: CatRenderState?, time: Double = 7.3, view: HomeRoom? = nil) -> PixelCanvas {
    RoomRenderer.render(room, options: RoomRenderOptions(time: time, cat: cat, view: view))
}

let seasons: [(name: String, month: Int)] = [("winter", 1), ("spring", 4), ("summer", 7), ("autumn", 10)]
let stageSpot = (x: 80.0, y: 101.0)

// MARK: - Interactive stage
//
// The main room in each season by day and by night, split the way the app splits it for
// widgets: what's behind Bitz, Bitz, and what stands in front. Bitz's frames are cut from
// the renderer's own cat layer at the stage spot, so they carry the scene's lighting.

/// One frame cell: the point between the front paws sits at `anchor`.
let cell = (width: 48, height: 48)
let anchor = (x: 24, y: 43)
let columns = 12

func layers(_ room: RoomSnapshot, cat: CatRenderState?, time: Double) -> RoomLayers {
    RoomRenderer.layers(room, options: RoomRenderOptions(time: time, cat: cat, view: .living))
}

var manifest = "// Generated by tools/bitz-art from the Bitz renderer. Do not edit by hand.\n"
manifest += "window.BITZ_STAGE = {\n  size: [160, 112], cell: [\(cell.width), \(cell.height)], anchor: [\(anchor.x), \(anchor.y)], columns: \(columns),\n  scenes: {\n"

/// Asleep on the cushion, as the app plans it for an autumn night (the same spot every season).
let nightRest = CatRenderState(plan: homeRoom(.living, hour: 22, minute: 40, month: 10).plan.resting)

for season in seasons {
    for (phase, hour) in [("day", 13), ("night", 22)] {
        let name = "\(season.name)-\(phase)"
        let room = homeRoom(.living, hour: hour, minute: hour == 22 ? 40 : 30, month: season.month)
        // By day Bitz sits on the rug; by night Bitz is asleep where the app puts them.
        let rest = phase == "day"
            ? CatRenderState(x: stageSpot.x, y: stageSpot.y, facing: .right, mode: .resting(.sit, elapsed: 2))
            : nightRest
        let spot = (x: Int(rest.x.rounded()), y: Int(rest.y.rounded()))
        let still = layers(room, cat: rest, time: 7.3)
        save(still.background, "stage-\(name)-bg")
        save(still.foreground, "stage-\(name)-fg")
        // Still pictures of the whole scene (the no-JavaScript hero and the homepage).
        if ["autumn-day", "autumn-night", "winter-day"].contains(name) {
            save(render(room, cat: rest, view: .living), "scene-\(name)")
        }

        var frames: [PixelCanvas] = []
        var seen: [Data: Int] = [:]
        var sequences: [(String, [Int])] = []
        // Just petted: the engine's "happy" moment, which the renderer draws with the
        // celebrate pose, a cloud of hearts and purr lines (asleep, Bitz keeps sleeping).
        let pettedRoom = homeRoom(.living, hour: hour, minute: hour == 22 ? 40 : 30, month: season.month) { state, date in
            state.lastPettedAt = date.addingTimeInterval(-1)
        }
        func add(_ sequence: String, _ states: [(CatRenderState, Double)], in source: RoomSnapshot? = nil) {
            var indices: [Int] = []
            for (state, time) in states {
                let lit = layers(source ?? room, cat: state, time: time).cat
                    .cropped(x: spot.x - anchor.x, y: spot.y - anchor.y, width: cell.width, height: cell.height)
                let data = PNGEncoder.encode(lit)
                if let index = seen[data] { indices.append(index); continue }
                seen[data] = frames.count
                indices.append(frames.count)
                frames.append(lit)
            }
            sequences.append((sequence, indices))
        }
        func at(_ facing: Facing, _ mode: CatRenderState.Mode) -> CatRenderState {
            CatRenderState(x: Double(spot.x), y: Double(spot.y), facing: facing, mode: mode)
        }
        if phase == "day" {
            for facing in [Facing.right, .left] {
                let f = facing == .right ? "r" : "l"
                add("walk-\(f)", (0..<4).map { (at(facing, .walking(frame: $0, gait: .walk)), 7.3) })
                add("turn-\(f)", [(at(facing, .turning), 7.3)])
                let rests: [(String, RestActivity, Int)] = [
                    ("sit", .sit, 24), ("loaf", .loaf, 16), ("groom", .groom, 16),
                    ("look", .lookAround, 16), ("blink", .slowBlink, 12),
                ]
                for (sequence, activity, count) in rests {
                    add("\(sequence)-\(f)", (0..<count).map {
                        let t = 1 + Double($0) * 0.25
                        return (at(facing, .resting(activity, elapsed: t)), 7.3 + t)
                    })
                }
                add("pet-\(f)", (0..<12).map {
                    let t = Double($0) * 0.25
                    return (at(facing, .resting(.celebrate, elapsed: t)), 7.3 + t)
                }, in: pettedRoom)
            }
        } else {
            // Asleep: petting only brings a sleepy purr, so the night stage has one pose.
            let mode: CatRenderState.Mode = {
                if case .resting(let activity, _) = rest.mode { return .resting(activity, elapsed: 2) }
                return .resting(.curl, elapsed: 2)
            }()
            let sleeping = (0..<16).map { i -> (CatRenderState, Double) in
                var state = rest
                if case .resting(let activity, _) = mode { state.mode = .resting(activity, elapsed: 1 + Double(i) * 0.25) }
                return (state, 7.3 + Double(i) * 0.25)
            }
            add("sleep", sleeping)
        }
        var sheet = PixelCanvas(width: columns * cell.width, height: ((frames.count + columns - 1) / columns) * cell.height)
        for (i, frame) in frames.enumerated() {
            sheet.composite(frame, x: (i % columns) * cell.width, y: (i / columns) * cell.height)
        }
        save(sheet, "stage-\(name)-cat")
        manifest += "    \"\(name)\": { spot: [\(spot.x), \(spot.y)], sequences: {"
        manifest += sequences.map { "\"\($0.0)\": [\($0.1.map(String.init).joined(separator: ","))]" }.joined(separator: ", ")
        manifest += "} },\n"
        print(name, "spot", spot, "behavior", room.behavior, "petted", pettedRoom.behavior, "frames", frames.count)
    }
}
manifest += "  }\n};\n"
try manifest.write(to: output.appendingPathComponent("stage.js"), atomically: true, encoding: .utf8)

