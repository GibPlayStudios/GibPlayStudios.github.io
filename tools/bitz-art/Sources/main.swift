// MARK: - Portraits: growth stages and clothing packs

func portrait(stage: GrowthStage = .adult, outfits: [OutfitSlot: Outfit] = [:], activity: RestActivity = .sit) -> PixelCanvas {
    let art = CatArtist.render(CatRenderState(x: 0, y: 0, facing: .right, mode: .resting(activity, elapsed: 2)),
                               outfits: outfits, time: 1.3, stage: stage, look: CatLook(mood: .content))
    var canvas = PixelCanvas(width: 40, height: 36)
    canvas.ellipse(cx: 20, cy: 32.5, rx: 9, ry: 1.6, RGBA(30, 16, 28, 70))
    canvas.composite(art.canvas, x: 20 - art.feet.x, y: 32 - art.feet.y)
    return canvas
}

var portraits: [(String, PixelCanvas)] = GrowthStage.allCases.map { ("stage-\($0.rawValue)", portrait(stage: $0)) }
for pack in [ClothingPack.stargazer, .sailor, .royal, .rainyDay, .snowDay, .explorer] {
    var outfits: [OutfitSlot: Outfit] = [:]
    for outfit in pack.outfits { outfits[outfit.slot] = outfit }
    portraits.append(("wear-\(pack.rawValue)", portrait(outfits: outfits)))
}
// One shared crop (the union of every portrait's visible pixels, plus a margin) keeps
// sizes comparable: a kitten still looks smaller than a grown-up.
var minX = 40, minY = 36, maxX = 0, maxY = 0
for (_, canvas) in portraits {
    for y in 0..<canvas.height { for x in 0..<canvas.width where canvas[x, y].a > 0 {
        minX = min(minX, x); maxX = max(maxX, x); minY = min(minY, y); maxY = max(maxY, y)
    } }
}
let side = max(maxX - minX, maxY - minY) + 3
let cropX = max(0, (minX + maxX) / 2 - side / 2), cropY = max(0, maxY + 2 - side)
for (name, canvas) in portraits {
    save(canvas.cropped(x: cropX, y: cropY, width: min(side, 40 - cropX), height: min(side, 36 - cropY)), name)
}
print("portrait crop", cropX, cropY, side)

// MARK: - Widgets and the Charging Room

func widgetArt(_ room: RoomSnapshot, aspect: Double) -> PixelCanvas {
    let cat = room.isHome ? CatRenderState(plan: room.plan.resting) : nil
    let full = RoomRenderer.render(room, options: RoomRenderOptions(time: 2, cat: cat))
    let c = WidgetFraming.crop(for: room, aspect: aspect, rows: 72)
    return full.cropped(x: c.x, y: c.y, width: c.width, height: c.height)
}

func liveRoom(hour: Int, minute: Int = 0, month: Int = 10, behavior: BitzBehavior? = nil,
              configure: (inout BitzState, Date) -> Void = { _, _ in }) -> RoomSnapshot {
    let date = calendar.date(from: DateComponents(year: 2026, month: month, day: 6, hour: hour, minute: minute))!
    var state = BitzState(now: date.addingTimeInterval(-3600), seed: "quiet-1")
    state.introTripPlanned = true
    state.tripsPlannedThrough = DayKey(year: 2100, month: 1, day: 1)
    state.ownedOutfits = Set(siteOutfit.values)
    state.equipped = siteOutfit
    configure(&state, date)
    let room = EnvironmentEngine.snapshot(state, at: date, calendar: calendar)
    return behavior.map { room.forcing($0, seed: "quiet-1") } ?? room
}

